// Generate the legacy printing-id alias table: every definition id or
// printing id from the pre-consolidation catalog (default: the parent of the
// consolidation merge) that no longer resolves, mapped to the canonical card
// id that owned it. Stored deck data and art selections authored before the
// canonical-card consolidation may reference those ids.
//
//   node --experimental-strip-types scripts/generate-legacy-printing-aliases.mjs [--ref <git-ref>]
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const refIndex = process.argv.indexOf("--ref");
const REF =
  refIndex === -1 ? "9780c13e0c374fbeb4c1775a5a71825e0241b483^" : process.argv[refIndex + 1];
const REPO_ROOT = execSync("git rev-parse --show-toplevel", { encoding: "utf8" }).trim();
const CARDS_PREFIX = "submodules/one-piece/packages/cards/src/cards/";

// the current catalog defines which ids still resolve on their own
const { allCards } = await import(join(__dirname, "..", "src", "index.ts"));
const currentIds = new Set();
for (const card of allCards) {
  currentIds.add(card.id);
  for (const printing of card.printings) currentIds.add(printing.id);
}

const tree = execSync(`git ls-tree -r --name-only ${REF} ${CARDS_PREFIX}`, {
  cwd: REPO_ROOT,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
})
  .trim()
  .split("\n")
  .filter((p) => p.endsWith(".ts") && !p.endsWith(".i18n.ts") && !p.endsWith("/index.ts"));

const oldRefs = new Map(); // old id -> canonical card id
let unresolvedCanonical = 0;
for (const full of tree) {
  const text = execSync(`git show ${REF}:${full}`, {
    cwd: REPO_ROOT,
    encoding: "utf8",
    maxBuffer: 4 * 1024 * 1024,
  });
  const id = /^ {2}id: "([^"]+)",$/m.exec(text)?.[1];
  const printingIds = [...text.matchAll(/^ {6}id: "([^"]+)",$/gm)].map((m) => m[1]);
  if (!id) continue;
  // spread-copy defs inherit canonicalId and never declare it; per rules
  // 2-14 / 5-1-2-3 the canonical card is the id's printed number prefix.
  let canonicalId = /^ {2}canonicalId: "([^"]+)",$/m.exec(text)?.[1];
  if (!canonicalId) {
    const numberPrefix = id.replace(/_.*$/, "");
    canonicalId = currentIds.has(numberPrefix) ? numberPrefix : (unresolvedCanonical++, null);
  }
  if (!canonicalId) continue;
  if (!oldRefs.has(id)) oldRefs.set(id, canonicalId);
  for (const printingId of printingIds) {
    if (!oldRefs.has(printingId)) oldRefs.set(printingId, canonicalId);
  }
}
if (unresolvedCanonical > 0) {
  console.warn(`WARNING: ${unresolvedCanonical} defs with unresolvable canonical ids skipped`);
}

const aliases = {};
for (const [oldId, canonical] of [...oldRefs].sort(([a], [b]) => a.localeCompare(b))) {
  if (currentIds.has(oldId)) continue;
  aliases[oldId] = canonical;
}

const count = Object.keys(aliases).length;
const header = `// Generated by scripts/generate-legacy-printing-aliases.mjs --ref ${REF}.
// Do not edit by hand. Maps definition/printing ids that existed before the
// canonical-card consolidation (and no longer resolve) to the canonical card
// id that owned them, so stored deck data and art selections keep resolving.
export const legacyPrintingIdAliases: Readonly<Record<string, string>> = ${JSON.stringify(aliases, null, 2)};
`;
writeFileSync(join(__dirname, "..", "src", "legacy-printing-id-aliases.generated.ts"), header);
console.log(`legacy aliases: ${count} of ${oldRefs.size} pre-consolidation ids`);
