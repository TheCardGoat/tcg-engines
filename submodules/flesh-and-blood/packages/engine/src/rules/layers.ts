import type {
  FabCondition,
  FabEffect,
  FabModalAbility,
  FabTrigger,
  FabZone,
} from "@tcg/flesh-and-blood-types";
import type { CommittedEvent, FabEventBindings, FabLayerId, FabObjectSnapshot } from "./events.ts";
import type { FabAttackTarget } from "../state.ts";
import type { FabCardPropertyState } from "../cards.ts";
import type { FabOptionalTriggerAutomation } from "./process.ts";
import type { FabTargetMap, FabTargetRef } from "./targets.ts";

interface FabLayerBase {
  readonly layerId: FabLayerId;
  readonly controllerId: string;
  readonly source: FabObjectSnapshot;
  readonly modes: readonly string[];
  readonly bindings: FabEventBindings;
  /** A resolving asset payment only succeeds after its journal commits. */
  readonly effectPaymentReceipts?: Readonly<Record<string, FabEffectPaymentReceipt>>;
}

/**
 * A declared layer publicly identifies its source (CR 3.15.1, 5.2.4b,
 * 5.4.7b). Preserve that disclosure on the layer's historical snapshot so
 * effects generated by it retain their known provenance (CR 6.2.2a).
 * This does not turn the live card face up or change its event-boundary LKI.
 */
export function disclosedFabLayerSource(source: FabObjectSnapshot): FabObjectSnapshot {
  return source.visibility === "public" ? source : { ...source, visibility: "public" };
}

export interface FabEffectPaymentReceipt {
  readonly status: "committed" | "failed";
  readonly playerId: string;
  readonly costType: "resources" | "life";
  readonly amount: number;
  readonly pitches: readonly { readonly instanceId: string; readonly incarnation: number }[];
  readonly eventIds: readonly CommittedEvent["eventId"][];
}

export interface FabCardResolutionStep {
  /** Printed face and ability batch whose instructions this step resolves. */
  readonly faceId: import("@tcg/flesh-and-blood-types").FabFaceId;
  readonly abilityIds: readonly string[];
  readonly effects: readonly FabEffect[];
  readonly targets: FabTargetMap;
}

export interface FabCardLayer extends FabLayerBase {
  readonly kind: "card";
  /** Authoritative selected face(s) for this stack incarnation. */
  readonly propertyState: FabCardPropertyState;
  readonly playTiming: import("./legality-quotes.ts").FabPlayTiming;
  readonly playedFrom: FabZone;
  readonly role: "action" | "instant" | "attack" | "attack-reaction" | "defense-reaction";
  /**
   * Keywords that apply to this card layer as a whole. For meld this is the
   * union across both printed faces and their resolution-ability layer
   * keywords, so a right-side keyword remains observable after the cursor
   * advances and go again is applied only after the final step.
   */
  readonly keywords: readonly string[];
  readonly instanceId: string;
  /** Ordered printed ability batches. A face change is the only boundary that opens priority. */
  readonly resolutionPlan: {
    readonly steps: readonly [FabCardResolutionStep, ...FabCardResolutionStep[]];
    readonly cursor: number;
  };
  readonly attackTarget: FabAttackTarget | null;
  /** Additional heroes attacked alongside the primary (Bolfar multi-target). */
  readonly additionalAttackTargets?: readonly FabAttackTarget[];
}

export type FabActivatedLayer = FabLayerBase &
  (
    | {
        readonly kind: "activated";
        readonly role: "ability";
        readonly abilityId: string;
        readonly effect: FabEffect;
        readonly keywords: readonly string[];
        readonly targets: FabTargetMap;
        readonly equipDestination: "head" | "chest" | "arms" | "legs" | null;
        readonly attackTarget: null;
        readonly additionalAttackTargets?: readonly FabAttackTarget[];
      }
    | {
        readonly kind: "activated";
        readonly role: "attack";
        /**
         * CR 1.4.3 / 1.4.4: an activated Attack ability is itself an
         * attack-proxy, while an ability that generates attack (with) is an
         * attack-layer. Both declare attack targets, but only the proxy opens
         * the combat chain before this layer resolves.
         */
        readonly attackKind: "proxy" | "layer";
        readonly abilityId: string;
        readonly effect: FabEffect;
        readonly keywords: readonly string[];
        readonly targets: FabTargetMap;
        readonly equipDestination: "head" | "chest" | "arms" | "legs" | null;
        readonly attackTarget: FabAttackTarget;
        readonly additionalAttackTargets?: readonly FabAttackTarget[];
      }
  );

export interface FabTriggeredLayer extends FabLayerBase {
  readonly kind: "triggered";
  readonly abilityId: string;
  readonly trigger: FabTrigger;
  readonly abilityCondition?: FabCondition;
  readonly triggeringEvent: CommittedEvent | null;
  readonly resolution: FabTriggeredResolution;
  readonly keywords: readonly string[];
  readonly targets: FabTargetMap;
  /** Owner-private behavior captured when this exact trigger was created. */
  readonly optionalTriggerAutomation?: FabOptionalTriggerAutomation;
}

export function activeFabCardResolutionStep(layer: FabCardLayer): FabCardResolutionStep {
  const step = layer.resolutionPlan.steps[layer.resolutionPlan.cursor];
  if (!step) throw new Error(`Card layer ${layer.layerId} has an invalid resolution cursor.`);
  return step;
}

export function fabLayerKeywords(layer: FabRulesStackLayer): readonly string[] {
  return layer.keywords;
}

export function fabLayerTargets(layer: FabRulesStackLayer): FabTargetMap {
  return layer.kind === "card" ? activeFabCardResolutionStep(layer).targets : layer.targets;
}

/**
 * Promote named hero-target declarations into semantic layer bindings.
 * The target map remains the exact declaration record while `{ binding }`
 * payer, chooser, and filter consumers receive the same stable player id.
 */
export function fabDeclaredPlayerBindings(targets: FabTargetMap): FabEventBindings {
  const bindings: Record<string, string> = {};
  for (const [key, answers] of Object.entries(targets)) {
    const marker = ":player@";
    const markerIndex = key.lastIndexOf(marker);
    if (markerIndex < 0 || answers.length !== 1) continue;
    const answer = answers[0];
    if (!answer || answer.kind !== "player") continue;
    const binding = key.slice(markerIndex + marker.length);
    if (binding.length > 0) bindings[binding] = answer.playerId;
  }
  return bindings;
}

/**
 * Return a layer with one declaration-time target answer persisted on it.
 *
 * Card layers keep targets on their active printed resolution step, while
 * activated and triggered layers own a single target map. Keeping this shape
 * distinction behind one exhaustive helper prevents continuation handlers
 * from accidentally writing resolution-time choices into process-local state.
 */
export function withFabLayerTarget(
  layer: FabRulesStackLayer,
  targetKey: string,
  targets: readonly FabTargetRef[],
): FabRulesStackLayer {
  switch (layer.kind) {
    case "card": {
      const cursor = layer.resolutionPlan.cursor;
      const current = activeFabCardResolutionStep(layer);
      const mutableSteps = [...layer.resolutionPlan.steps];
      mutableSteps[cursor] = {
        ...current,
        targets: { ...current.targets, [targetKey]: targets },
      };
      const first = mutableSteps[0];
      if (!first) throw new Error(`Card layer ${layer.layerId} has no resolution step.`);
      const steps: readonly [FabCardResolutionStep, ...FabCardResolutionStep[]] = [
        first,
        ...mutableSteps.slice(1),
      ];
      return { ...layer, resolutionPlan: { ...layer.resolutionPlan, steps } };
    }
    case "activated":
    case "triggered":
      return { ...layer, targets: { ...layer.targets, [targetKey]: targets } };
    default:
      return assertNeverLayer(layer);
  }
}

/** Return a layer with one resolution-time semantic binding persisted on it. */
export function withFabLayerBinding(
  layer: FabRulesStackLayer,
  binding: string,
  value: FabEventBindings[string],
): FabRulesStackLayer {
  return { ...layer, bindings: { ...layer.bindings, [binding]: value } };
}

export type FabTriggeredResolution =
  | { readonly kind: "effect"; readonly effect: FabEffect }
  | {
      readonly kind: "modal";
      readonly ability: Pick<FabModalAbility, "modal" | "modes" | "effect" | "condition">;
    };

/** Adding a new layer kind breaks every non-exhaustive resolver. */
export type FabRulesStackLayer = FabCardLayer | FabActivatedLayer | FabTriggeredLayer;

export function assertNeverLayer(value: never): never {
  throw new Error(`Unsupported FAB stack layer: ${JSON.stringify(value)}`);
}
